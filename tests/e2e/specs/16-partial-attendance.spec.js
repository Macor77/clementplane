test('switching realization status preserves draft rows until explicitly removed (API simulated)', async ({ page }) => {
  const api = await fixture(page); await page.goto(`/formateur/missions/personnelles/${id}`);
  await page.getByRole('combobox', { name: 'Formation réalisée', exact: true }).selectOption('done');
  await page.getByLabel('Apprenants entièrement formés', { exact: true }).fill('4');
  const details = page.locator('details.activity-partial-attendance'); await details.locator('summary').click();
  await details.getByRole('button', { name: '+ Ajouter une ligne' }).click();
  await details.getByLabel('Nombre d’apprenants partiellement formés — ligne 1').fill('1');
  await details.getByLabel('Durée suivie en heures — ligne 1').fill('1');
  await page.getByRole('combobox', { name: 'Formation réalisée', exact: true }).selectOption('not_done');
  await page.getByRole('button', { name: 'Enregistrer le bilan' }).click();
  await expect(page.getByRole('alert')).toContainText('confirmez la réalisation'); expect(api.saved()).toBeNull();
  await expect(details.getByLabel('Durée suivie en heures — ligne 1')).toHaveValue('1');
  await details.getByRole('button', { name: 'Supprimer la participation partielle 1' }).click();
  await page.getByRole('button', { name: 'Enregistrer le bilan' }).click(); await expect(page.getByText('Bilan enregistré.', { exact: true })).toBeVisible();
  expect(api.saved().report.partial_attendance).toEqual([]);
});
